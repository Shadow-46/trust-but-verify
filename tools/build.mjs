// Generate dist/core/**/*.js from core/**/*.ts using Node's built-in type stripper.
//
// Why: the judge starts a new Node process for every request and installs
// nothing. Stripping TypeScript at runtime costs ~270 ms per request; shipping
// pre-stripped JavaScript brings the adapter import down to ~30 ms. The output
// is committed; tests/build.test.ts fails if it is stale.
//
// Usage: node tools/build.mjs [outDir]   (default: dist)
import { stripTypeScriptTypes } from "node:module";
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "core");
const OUT = resolve(ROOT, process.argv[2] ?? "dist");

const HEADER = "// GENERATED by tools/build.mjs from the TypeScript source in core/. Do not edit.\n";

function walk(dir) {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? walk(p) : [p];
    });
}

export function build(outDir = OUT) {
  rmSync(join(outDir, "core"), { recursive: true, force: true });
  const written = [];
  for (const file of walk(SRC).filter((f) => f.endsWith(".ts"))) {
    const js = stripTypeScriptTypes(readFileSync(file, "utf8"), { mode: "strip" })
      // Relative imports point at .ts sources; the generated files are .js.
      .replace(/(from\s+["']\.{1,2}\/[^"']+)\.ts(["'])/g, "$1.js$2")
      .replace(/(import\(\s*["']\.{1,2}\/[^"']+)\.ts(["'])/g, "$1.js$2");
    const target = join(outDir, relative(ROOT, file)).replace(/\.ts$/, ".js");
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, HEADER + js);
    written.push(relative(outDir, target).split("\\").join("/"));
  }
  return written;
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const files = build();
  process.stdout.write(`built ${files.length} files into ${relative(ROOT, OUT) || "."}\n`);
}
